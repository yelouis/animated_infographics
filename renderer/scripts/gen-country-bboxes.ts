import * as fs from "node:fs";
import * as path from "node:path";
import * as d3 from "d3-geo";
import * as topojson from "topojson-client";
import type { Topology } from "topojson-specification";

interface CountryProperties {
  name?: string;
}

interface CountryFeature extends GeoJSON.Feature<GeoJSON.Geometry, CountryProperties> {
  id?: string | number;
}

const projectRoot = path.resolve(__dirname, "../..");
const countryInfoPath = path.join(projectRoot, "data/vendor/countryInfo.txt");
const outPath = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.join(projectRoot, "data/geo/country_bboxes.json");

if (!fs.existsSync(countryInfoPath)) {
  console.error(`countryInfo.txt not found at ${countryInfoPath}`);
  process.exit(1);
}

const countryInfo = fs.readFileSync(countryInfoPath, "utf-8");
const numToIso3: Record<string, string> = {};

for (const line of countryInfo.split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const parts = line.split("\t");
  if (parts.length > 2) {
    const iso3 = parts[1].trim();
    const num = parts[2].trim().padStart(3, "0");
    if (iso3 && num) {
      numToIso3[num] = iso3;
    }
  }
}

const worldAtlasPkg = require.resolve("world-atlas/countries-50m.json");
const topoData = JSON.parse(fs.readFileSync(worldAtlasPkg, "utf-8")) as Topology;
const geoCollection = topojson.feature(topoData, topoData.objects.countries);
const features = (
  "features" in geoCollection ? geoCollection.features : []
) as unknown as CountryFeature[];

const bboxes: Record<string, [number, number, number, number]> = {};

for (const feature of features) {
  if (!feature.id) {
    console.log(`Skipping feature without id: ${feature.properties?.name || "unknown"}`);
    continue;
  }
  const idStr = String(feature.id).padStart(3, "0");
  const iso3 = numToIso3[idStr];
  if (!iso3) {
    console.log(`Skipping unmapped id ${feature.id} (${feature.properties?.name || "unknown"})`);
    continue;
  }
  const bounds = d3.geoBounds(feature);
  bboxes[iso3] = [bounds[0][0], bounds[0][1], bounds[1][0], bounds[1][1]];
}

const sortedKeys = Object.keys(bboxes).sort();
const result: Record<string, [number, number, number, number] | string> = {
  $comment: "GENERATED by renderer/scripts/gen-country-bboxes.ts — DO NOT EDIT",
};

for (const key of sortedKeys) {
  result[key] = bboxes[key];
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, JSON.stringify(result, null, 2) + "\n", "utf-8");
console.log(`Wrote ${sortedKeys.length} country bboxes to ${outPath}`);
